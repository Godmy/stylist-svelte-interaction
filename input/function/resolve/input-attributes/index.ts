/** Native control attributes, excluding the composition's data and presentation API. */
export function resolveInputAttributes(
	props: object,
	excluded: readonly string[] = []
): Record<string, unknown> {
	const composition = new Set([
		'class',
		'value',
		'children',
		'variant',
		'size',
		'block',
		'error',
		'errors',
		'label',
		'labelId',
		'helperText',
		'helpText',
		'showErrors',
		'showHelperWhenError',
		'showRequiredIndicator',
		'showPassword',
		'allowTogglePassword',
		'showPasswordStrength',
		'autoResize',
		'buttonLabel',
		'buttonVariant',
		'buttonDisabled',
		'onButtonClick',
		'htmlFor',
		'onValueInput',
		'onValueChange',
		'onInput',
		'onChange',
		'inputClass',
		'buttonClass',
		'buttonWrapperClass',
		'ariaLabel',
		'text',
		'description',
		'subtitle',
		'icon',
		'focused',
		'invalid',
		'tags',
		'maxTags',
		'delimiter',
		'validator',
		'tagClass',
		'removeButtonClass',
		'toolbarClass',
		'editorClass',
		'showToolbar',
		'toolbarPosition',
		...excluded
	]);
	return Object.fromEntries(Object.entries(props).filter(([key]) => !composition.has(key)));
}
