export interface RecipeInputStepper {
	/** Текущее значение */
	value?: number;
	/** Минимально допустимое значение */
	min?: number;
	/** Максимально допустимое значение */
	max?: number;
	/** Шаг изменения за одно нажатие */
	step?: number;
	/** Подпись для aria-label контейнера и кнопок */
	label?: string;
	/** Заблокировать управление */
	disabled?: boolean;
	/** Размер контрола: масштабирует текст и кнопки (em-based) */
	size?: 'sm' | 'md' | 'lg';
	/** Фон контрола: произвольное CSS-значение (цвет, градиент, прозрачность) */
	background?: string;
	/** Дополнительный класс на корневой элемент */
	class?: string;
	/** Колбэк с новым значением после изменения */
	onChange?: (value: number) => void;
}
